/**
 * Defensive HTML escaping utility for Centrly UI.
 * Sanitizes user/database inputs before injection into innerHTML or template strings.
 */
export function escapeHtml(str) {
  if (str === null || str === undefined) return '';
  return String(str).replace(/[&<>"']/g, (c) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;',
  }[c]));
}
